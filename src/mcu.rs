    fn cmd(mcu: &mut Mcu, f: &mut Fake, seq: u8, payload: &[u8]) -> Vec<Vec<u8>> {
        let mut blk = [0u8; 64];
        let n = encode_block(&mut blk, seq, payload);
        mcu.rx_space()[..n].copy_from_slice(&blk[..n]);
        mcu.rx_commit(n, f);
        core::mem::take(&mut f.out)
    }

