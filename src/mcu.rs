pub trait Board {
    /// 32-bit free running clock at `CLOCK_FREQ`.
    fn now(&mut self) -> u32;
    /// Transmit one framed block.
    fn write(&mut self, block: &[u8]);
    /// Force all outputs to their safe state (heaters/drivers off).
    fn safe_outputs(&mut self) {}
    /// Configure `pin` as output (if needed) and drive it.
    fn set_out(&mut self, _pin: u32, _value: bool) -> Res {
        Err("Invalid output pin")
    }
    /// Prepare `pin` for `adc_read`.
    fn adc_setup(&mut self, _pin: u32) -> Res {
        Err("Invalid analog pin")
    }
    /// One ADC sample, in units of `ADC_MAX`.
    fn adc_read(&mut self, _pin: u32) -> u16 {
        0
    }
    /// Configure `pin` as input.
    fn in_setup(&mut self, _pin: u32, _pull_up: bool) -> Res {
        Err("Invalid input pin")
    }
    fn get_in(&mut self, _pin: u32) -> bool {
        false
    }
    /// Set up the (only) hardware I2C bus.
    fn i2c_setup(&mut self, _rate: u32) -> Res {
        Err("Unsupported i2c bus")
    }
    /// Write `data` to 7-bit `addr`; returns an `i2c_bus_status` value.
    /// Boards may defer the transfer outside their lock and report success.
    fn i2c_write(&mut self, _addr: u8, _data: &[u8]) -> u8 {
        1
    }
}

#[derive(Default)]
enum Obj {
    #[default]
    Free,
    Dout(DigitalOut),
    Ain(AnalogIn),
    Stepper(Stepper),
    Endstop(Endstop),
    Trsync(Trsync),
    Buttons(Buttons),
    /// I2C device: 7-bit address.
    I2c(u8),
}

/// ponytail: fixed pool; a JOKER printer.cfg uses well under this.
pub const MAX_OIDS: usize = 32;

enum Arg<'a> {
    Int(u32),
    Buf(&'a [u8]),
}

const RX_SIZE: usize = RECEIVE_WINDOW as usize;
const MAX_ARGS: usize = 10;
/// Command args, zero-padded to `MAX_ARGS`: constant indexes are checked at
/// compile time, so handlers carry no runtime bounds checks.
pub type Args = [u32; MAX_ARGS];
/// Args after the leading oid.
pub type Tail = [u32; MAX_ARGS - 1];

fn tail(a: &Args) -> &Tail {
    let [_, t @ ..] = a;
    t
}

pub struct Mcu {
    rx: [u8; RX_SIZE],
    fill: usize,
    next_seq: u8,
    shutdown_reason: Option<u16>,
    oid_count: Option<u8>,
    config_crc: u32,
    finalized: bool,
    // stats (basecmd.c stats_update)
    last_task: Option<u32>,
    stats_send_time: u32,
    stats_high: u32,
    count: u32,
    sum: u32,
    sumsq: u32,
    objs: [Obj; MAX_OIDS],
    pool: Pool,
}

fn reason_id(s: &str) -> u16 {
    let i = STATIC_STRINGS.iter().position(|x| *x == s).expect("unknown static string");
    i as u16 + STATIC_STRING_MIN
}

/// True for `%*s`/`%.*s`/`%s` params (length-prefixed bytes).
fn param_is_buf(fmt: &str) -> impl Iterator<Item = bool> + '_ {
    fmt.split('%').skip(1).map(|p| p.trim_start_matches(['.', '*']).starts_with('s'))
}

/// One decoded command; `cmd` is None on a parse error (`err` says which).
pub struct Parsed {
    cmd: Option<(u32, Kind)>,
    err: &'static str,
    args: Args,
    nargs: usize,
    /// Bytes of the (single) buffer param, if any.
    buf: [u8; MESSAGE_MAX],
}

/// Decode the first command in payload `p`; returns it and the rest
/// (empty on error).
pub fn parse(mut p: &[u8]) -> (Parsed, &[u8]) {
    let mut c = Parsed { cmd: None, err: "Command parser error", args: [0; MAX_ARGS], nargs: 0, buf: [0; MESSAGE_MAX] };
    let Some((cmd, n)) = decode_vlq(p) else { return (c, &[]) };
    p = &p[n..];
    let Some(&(kind, fmt)) = MESSAGES.get(cmd as usize).filter(|(k, _)| *k != Kind::Resp) else {
        c.err = "Invalid command";
        return (c, &[]);
    };
    for is_buf in param_is_buf(fmt) {
        // ponytail: one buffer param per command (true for all we accept)
        let Some((v, n)) = decode_vlq(p) else { return (c, &[]) };
        p = &p[n..];
        if is_buf {
            let (Some(d), Some(rest)) = (p.get(..v as usize), p.get(v as usize..)) else { return (c, &[]) };
            c.buf[..d.len()].copy_from_slice(d);
            p = rest;
        }
        c.args[c.nargs] = v;
        c.nargs += 1;
    }
    c.cmd = Some((cmd, kind));
    (c, p)
}

/// Typed `&mut` accessors into `objs`; wrong variant or oid -> "Invalid oid type".
macro_rules! accessors {
    ($($name:ident: $var:ident => $ty:ty),* $(,)?) => {
        impl Mcu {
            $(fn $name(&mut self, oid: u32) -> Res<&mut $ty> {
                match self.objs.get_mut(oid as usize) {
                    Some(Obj::$var(x)) => Ok(x),
                    _ => Err("Invalid oid type"),
                }
            })*
        }
    };
}
accessors! {
    dout: Dout => DigitalOut, ain: Ain => AnalogIn, stepper: Stepper => Stepper,
    endstop: Endstop => Endstop, trsync: Trsync => Trsync, buttons: Buttons => Buttons, i2c: I2c => u8,
}

impl Mcu {
    pub const fn new() -> Self {
        Self {
            rx: [0; RX_SIZE],
            fill: 0,
            next_seq: 0,
            shutdown_reason: None,
            oid_count: None,
            config_crc: 0,
            finalized: false,
            last_task: None,
            stats_send_time: 0,
            stats_high: 0,
            count: 0,
            sum: 0,
            sumsq: 0,
            objs: [const { Obj::Free }; MAX_OIDS],
            pool: Pool::new(),
        }
    }

    /// Allocated oid range; timer scans stop here (hot path in the ISR).
    fn live(&self) -> usize {
        (self.oid_count.unwrap_or(0) as usize).min(MAX_OIDS)
    }

    pub fn is_shutdown(&self) -> bool {
        self.shutdown_reason.is_some()
    }

    /// Announce boot (Klipper sends "starting" from sched_main).
    pub fn start(&mut self, b: &mut impl Board) {
        b.safe_outputs();
        self.stats_send_time = b.now();
        self.send(b, id::STARTING, &[]);
    }

    /// Space left in the rx buffer for `push_rx`.
    pub fn rx_space(&mut self) -> &mut [u8] {
        &mut self.rx[self.fill..]
    }

    /// Mark `n` bytes written into `rx_space()` and process complete blocks.
    pub fn rx_commit(&mut self, n: usize, b: &mut impl Board) {
        self.fill += n;
        loop {
            match find_block(&self.rx[..self.fill]) {
                Frame::Incomplete => break,
                Frame::Skip(n) => self.consume(n),
                Frame::Ok { len, seq } => {
                    let mut block = [0u8; MESSAGE_MAX];
                    block[..len].copy_from_slice(&self.rx[..len]);
                    self.consume(len);
                    if self.accept(seq) {
                        let mut p = &block[MESSAGE_HEADER_SIZE..len - MESSAGE_TRAILER_SIZE];
                        while !p.is_empty() {
                            p = self.command(p, b);
                        }
                    }
                    self.ack(b);
                }
            }
        }
        if self.fill == RX_SIZE {
            self.fill = 0; // ponytail: garbage-filled buffer dropped; host retransmits
        }
    }

    /// Background task, call once per main loop iteration.
    pub fn task(&mut self, b: &mut impl Board) {
        self.run_timers(b);
        self.stats_task(b);
    }

    /// Stats half of `task`, for boards that run timers from an ISR.
    pub fn stats_task(&mut self, b: &mut impl Board) {
        let cur = b.now();
        let Some(start) = self.last_task.replace(cur) else { return };
        let diff = cur.wrapping_sub(start);
        self.count = self.count.wrapping_add(1);
        self.sum = self.sum.wrapping_add(diff);
        let add = if diff <= 0xffff {
            (diff * diff).div_ceil(STATS_SUMSQ_BASE)
        } else if diff <= 0xfffff {
            diff.div_ceil(STATS_SUMSQ_BASE) * diff
        } else {
            u32::MAX
        };
        self.sumsq = self.sumsq.saturating_add(add);
        if cur.wrapping_sub(self.stats_send_time) < CLOCK_FREQ * 5 {
            return;
        }
        let (c, s, q) = (self.count, self.sum, self.sumsq);
        self.send(b, id::STATS, &[Arg::Int(c), Arg::Int(s), Arg::Int(q)]);
        if cur < self.stats_send_time {
            self.stats_high += 1;
        }
        self.stats_send_time = cur;
        self.count = 0;
        self.sum = 0;
        self.sumsq = 0;
    }

    /// Enter shutdown (Klipper `shutdown()`); idempotent for the reason.
    pub fn shutdown(&mut self, b: &mut impl Board, reason: &str) {
        let cur = b.now();
        b.safe_outputs();
        for o in &mut self.objs {
            match o {
                Obj::Dout(d) => d.shutdown(b),
                Obj::Stepper(s) => s.stop(b, &mut self.pool),
                Obj::Trsync(t) => t.clear(),
                _ => {}
            }
        }
        let r = *self.shutdown_reason.get_or_insert(reason_id(reason));
        self.send(b, id::SHUTDOWN, &[Arg::Int(cur), Arg::Int(r as u32)]);
    }

    /// Earliest pending timer wake time, if any (for programming a HW alarm).
    pub fn next_wake(&self, now: u32) -> Option<u32> {
        // Overdue timers have negative offsets, so they sort first.
        let mut best: Option<i32> = None;
        let mut add = |t: &crate::io::Timer| {
            let d = t.wake.wrapping_sub(now) as i32;
            if t.active && best.is_none_or(|b| d < b) {
                best = Some(d);
            }
        };
        for o in &self.objs[..self.live()] {
            match o {
                Obj::Dout(d) => add(&d.t),
                Obj::Ain(a) => add(&a.t),
                Obj::Stepper(s) => add(&s.t),
                Obj::Endstop(e) => add(&e.t),
                Obj::Trsync(t) => {
                    add(&t.report);
                    add(&t.expire);
                }
                Obj::Buttons(x) => add(&x.t),
                Obj::Free | Obj::I2c(_) => {}
            }
        }
        best.map(|d| now.wrapping_add(d as u32))
    }

    /// Run due timers until the next one is at least `min_gap` ticks away;
    /// returns its wake time (for arming a HW alarm), or None when idle.
    pub fn service(&mut self, b: &mut impl Board, min_gap: u32) -> Option<u32> {
        loop {
            self.run_timers(b);
            let now = b.now();
            let wake = self.next_wake(now)?;
            if wake.wrapping_sub(now) as i32 >= min_gap as i32 {
                return Some(wake);
            }
        }
    }

    /// Run every due timer (Klipper timer dispatch). Called from the timer ISR
    /// on hardware and from `task` everywhere.
    pub fn run_timers(&mut self, b: &mut impl Board) {
        // Clock reads cost ~0.5 µs on ESP32: read once, refresh after events.
        let mut now = b.now();
        for oid in 0..self.live() {
            loop {
                let check = !self.is_shutdown();
                let due = |t: &crate::io::Timer| t.active && !before(now, t.wake);
                let r = match &mut self.objs[oid] {
                    Obj::Dout(d) if due(&d.t) => d.event(b).map(|_| None),
                    Obj::Ain(a) if due(&a.t) => a.event(b, check),
                    Obj::Stepper(s) if due(&s.t) => s.event(b, &mut self.pool).map(|_| None),
                    Obj::Endstop(e) if due(&e.t) => {
                        if let Some((ts, reason)) = e.event(b) {
                            self.trigger(b, ts, reason);
                        }
                        Ok(None)
                    }
                    Obj::Trsync(t) if due(&t.expire) => {
                        t.expire.active = false;
                        let r = t.expire_reason;
                        self.trigger(b, oid as u8, r);
                        Ok(None)
                    }
                    Obj::Buttons(x) if due(&x.t) => {
                        if x.event(b) {
                            let (ack, n, rep) = (x.ack_count, x.report_count as usize, x.reports);
                            let args = [Arg::Int(oid as u32), Arg::Int(ack as u32), Arg::Buf(&rep[..n])];
                            self.send(b, id::BUTTONS_STATE, &args);
                        }
                        Ok(None)
                    }
                    Obj::Trsync(t) if due(&t.report) => {
                        t.report_event();
                        Ok(None)
                    }
                    _ => break,
                };
                now = b.now();
                match r {
                    Err(e) => self.shutdown(b, e),
                    Ok(Some(n)) => {
                        let Obj::Ain(a) = &self.objs[oid] else { unreachable!() };
                        let (next, data) = (a.next_begin, a.data);
                        let args = [Arg::Int(oid as u32), Arg::Int(next), Arg::Buf(&data[..n])];
                        self.send(b, id::ANALOG_IN_STATE, &args);
                    }
                    Ok(None) => {}
                }
            }
        }
        // trsync_task: report pending states
        for oid in 0..self.live() {
            if let Obj::Trsync(t) = &mut self.objs[oid]
                && t.flags & motion::REPORT != 0 {
                    t.flags &= !motion::REPORT;
                    let args = [
                        Arg::Int(oid as u32),
                        Arg::Int((t.flags & motion::CAN_TRIGGER != 0) as u32),
                        Arg::Int(t.trigger_reason as u32),
                        Arg::Int(b.now()),
                    ];
                    self.send(b, id::TRSYNC_STATE, &args);
                }
        }
    }

    /// trsync_do_trigger: stop attached steppers once, flag a report.
    fn trigger(&mut self, b: &mut impl Board, ts: u8, reason: u8) {
        let Some(Obj::Trsync(t)) = self.objs.get_mut(ts as usize) else { return };
        if t.flags & motion::CAN_TRIGGER == 0 {
            return;
        }
        t.trigger_reason = reason;
        t.flags = (t.flags & !motion::CAN_TRIGGER) | motion::REPORT;
        self.detach(b, ts, true);
    }

    /// Unhook steppers from trsync `ts`, optionally stopping them.
    fn detach(&mut self, b: &mut impl Board, ts: u8, stop: bool) {
        for o in &mut self.objs {
            if let Obj::Stepper(s) = o
                && s.stop_on == Some(ts) {
                    s.stop_on = None;
                    if stop {
                        s.stop(b, &mut self.pool);
                    }
                }
        }
    }




    fn motion_cmd(&mut self, cmd: u32, a: &Args, b: &mut impl Board) -> Res {
        match cmd {
            id::CONFIG_STEPPER => {
                let s = Stepper::new(b, a[1], a[2], a[3] as i8, a[4]).map(Obj::Stepper);
                self.alloc(a[0], s)
            }
            id::QUEUE_STEP => {
                let Some(Obj::Stepper(s)) = self.objs.get_mut(a[0] as usize) else {
                    return Err("Invalid oid type");
                };
                s.queue_step(b, &mut self.pool, tail(a))
            }
            id::SET_NEXT_STEP_DIR => {
                self.stepper(a[0])?.set_next_dir(a[1] != 0);
                Ok(())
            }
            id::RESET_STEP_CLOCK => self.stepper(a[0])?.reset_clock(a[1]),
            id::STEPPER_GET_POSITION => {
                let pos = self.stepper(a[0])?.position();
                self.send(b, id::STEPPER_POSITION, &[Arg::Int(a[0]), Arg::Int(pos as u32)]);
                Ok(())
            }
            id::STEPPER_STOP_ON_TRIGGER => {
                self.trsync(a[1])?;
                let s = self.stepper(a[0])?;
                if s.stop_on.is_some() {
                    return Err("Can't add signal that is already active");
                }
                s.stop_on = Some(a[1] as u8);
                Ok(())
            }
            id::CONFIG_ENDSTOP => {
                let e = Endstop::new(b, a[1], a[2] != 0).map(Obj::Endstop);
                self.alloc(a[0], e)
            }
            id::ENDSTOP_HOME => {
                if a[3] != 0 {
                    self.trsync(a[6])?;
                }
                self.endstop(a[0])?.home(tail(a));
                Ok(())
            }
            id::ENDSTOP_QUERY_STATE => {
                let e = self.endstop(a[0])?;
                let (homing, next, pin) = (e.homing(), e.nextwake, e.pin);
                let v = b.get_in(pin);
                let args = [Arg::Int(a[0]), Arg::Int(homing as u32), Arg::Int(next), Arg::Int(v as u32)];
                self.send(b, id::ENDSTOP_STATE, &args);
                Ok(())
            }
            id::CONFIG_TRSYNC => self.alloc(a[0], Ok(Obj::Trsync(Trsync::default()))),
            id::TRSYNC_START => {
                self.trsync(a[0])?.start(tail(a));
                self.detach(b, a[0] as u8, false);
                Ok(())
            }
            id::TRSYNC_SET_TIMEOUT => {
                self.trsync(a[0])?.set_timeout(a[1]);
                Ok(())
            }
            id::TRSYNC_TRIGGER => {
                self.trsync(a[0])?;
                self.trigger(b, a[0] as u8, a[1] as u8);
                let t = self.trsync(a[0])?;
                let r = t.trigger_reason;
                // Keep trigger_reason: host re-queries it via trsync_trigger.
                t.flags = 0;
                t.report.active = false;
                t.expire.active = false;
                self.send(b, id::TRSYNC_STATE, &[Arg::Int(a[0]), Arg::Int(0), Arg::Int(r as u32), Arg::Int(0)]);
                Ok(())
            }
            _ => Err("Invalid command"),
        }
    }

    fn alloc(&mut self, oid: u32, o: Res<Obj>) -> Res {
        let slot = self
            .objs
            .get_mut(oid as usize)
            .filter(|s| matches!(s, Obj::Free) && oid < self.oid_count.unwrap_or(0) as u32)
            .ok_or("Can't assign oid")?;
        *slot = o?;
        Ok(())
    }




    fn io_cmd(&mut self, cmd: u32, a: &Args, buf: &[u8], b: &mut impl Board) -> Res {
        match cmd {
            id::CONFIG_DIGITAL_OUT => {
                let d = DigitalOut::new(b, a[1], a[2] != 0, a[3] != 0, a[4]).map(Obj::Dout);
                self.alloc(a[0], d)
            }
            id::SET_DIGITAL_OUT_PWM_CYCLE => self.dout(a[0])?.set_cycle(a[1]),
            id::QUEUE_DIGITAL_OUT => self.dout(a[0])?.queue(a[1], a[2]),
            id::UPDATE_DIGITAL_OUT => {
                let now = b.now();
                self.dout(a[0])?.update(b, now, a[1] != 0)
            }
            id::SET_DIGITAL_OUT => b.set_out(a[0], a[1] != 0),
            id::CONFIG_ANALOG_IN => {
                let o = AnalogIn::new(b, a[1]).map(Obj::Ain);
                self.alloc(a[0], o)
            }
            id::QUERY_ANALOG_IN => self.ain(a[0])?.query(tail(a)),
            id::CONFIG_BUTTONS => {
                let o = Buttons::new(a[1]).map(Obj::Buttons);
                self.alloc(a[0], o)
            }
            id::BUTTONS_ADD => self.buttons(a[0])?.add(b, a[1], a[2], a[3] != 0),
            id::BUTTONS_QUERY => self.buttons(a[0])?.query(tail(a)),
            id::BUTTONS_ACK => {
                self.buttons(a[0])?.ack(a[1] as u8);
                Ok(())
            }
            id::CONFIG_I2C => self.alloc(a[0], Ok(Obj::I2c(0))),
            id::I2C_SET_BUS => {
                if a[1] != 0 {
                    return Err("Unsupported i2c bus");
                }
                b.i2c_setup(a[2])?;
                *self.i2c(a[0])? = (a[3] & 0x7f) as u8;
                Ok(())
            }
            id::I2C_TRANSFER => {
                let addr = *self.i2c(a[0])?;
                // ponytail: writes only (SSD1306); reads answer NACK, empty.
                let st = if a[2] == 0 { b.i2c_write(addr, &buf[..a[1] as usize]) } else { 1 };
                let args = [Arg::Int(a[0]), Arg::Int(st as u32), Arg::Buf(&[])];
                self.send(b, id::I2C_RESPONSE, &args);
                Ok(())
            }
            _ => self.motion_cmd(cmd, a, b),
        }
    }

    fn consume(&mut self, n: usize) {
        self.rx.copy_within(n..self.fill, 0);
        self.fill -= n;
    }

    /// Sequence check for a framed block: true if in order (then run its
    /// payload through `command`). Follow with `ack` either way.
    pub fn accept(&mut self, seq: u8) -> bool {
        let ok = seq == self.next_seq;
        if ok {
            self.next_seq = (seq + 1) & 0x0f;
        }
        ok
    }

    /// Ack (in order) or nak (out of order): both are empty blocks with the current seq.
    pub fn ack(&mut self, b: &mut impl Board) {
        self.send_raw(b, &[]);
    }

/// Run the first command in payload `p`; returns the rest (empty after
    /// a parse error, which shuts down).
    pub fn command<'a>(&mut self, p: &'a [u8], b: &mut impl Board) -> &'a [u8] {
        let (c, rest) = parse(p);
        self.exec(&c, b);
        rest
    }

    /// Run a command from `parse`. Parsing needs no state, so callers can
    /// parse outside their lock and hold it only for this.
    pub fn exec(&mut self, c: &Parsed, b: &mut impl Board) {
        let Some((cmd, kind)) = c.cmd else {
            return self.shutdown(b, c.err);
        };
        if self.is_shutdown() && kind != Kind::CmdAny {
            let r = self.shutdown_reason.unwrap_or(0);
            self.send(b, id::IS_SHUTDOWN, &[Arg::Int(r as u32)]);
        } else {
            self.run(cmd, &c.args, &c.buf, b);
        }
    }

    fn run(&mut self, cmd: u32, a: &Args, buf: &[u8], b: &mut impl Board) {
        match cmd {
            id::IDENTIFY => {
                let off = (a[0] as usize).min(IDENTIFY_DATA.len());
                let end = (off + a[1] as usize).min(IDENTIFY_DATA.len());
                self.send(b, id::IDENTIFY_RESPONSE, &[Arg::Int(a[0]), Arg::Buf(&IDENTIFY_DATA[off..end])]);
            }
            id::GET_UPTIME => {
                let cur = b.now();
                let high = self.stats_high + (cur < self.stats_send_time) as u32;
                self.send(b, id::UPTIME, &[Arg::Int(high), Arg::Int(cur)]);
            }
            id::GET_CLOCK => {
                let cur = b.now();
                self.send(b, id::CLOCK, &[Arg::Int(cur)]);
            }
            id::GET_CONFIG => {
                let args = [
                    Arg::Int(self.finalized as u32),
                    Arg::Int(self.config_crc),
                    Arg::Int(self.is_shutdown() as u32),
                    Arg::Int(MOVE_COUNT as u32),
                ];
                self.send(b, id::CONFIG, &args);
            }
            id::FINALIZE_CONFIG => {
                self.config_crc = a[0];
                self.finalized = true;
            }
            id::ALLOCATE_OIDS => {
                if self.oid_count.is_some() {
                    return self.shutdown(b, "oids already allocated");
                }
                self.oid_count = Some(a[0] as u8);
            }
            id::CONFIG_RESET => {
                if !self.is_shutdown() {
                    return self.shutdown(b, "config_reset only available when shutdown");
                }
                self.oid_count = None;
                self.objs = [const { Obj::Free }; MAX_OIDS];
                self.pool = Pool::new();
                self.config_crc = 0;
                self.finalized = false;
                self.shutdown_reason = None;
            }
            id::EMERGENCY_STOP => self.shutdown(b, "Command request"),
            id::CLEAR_SHUTDOWN => {
                if self.shutdown_reason.take().is_none() {
                    self.shutdown(b, "Shutdown cleared when not shutdown");
                }
            }
            _ => {
                if let Err(e) = self.io_cmd(cmd, a, buf, b) {
                    self.shutdown(b, e);
                }
            }
        }
    }

    fn send(&mut self, b: &mut impl Board, msgid: u32, args: &[Arg]) {
        let mut buf = [0u8; MESSAGE_MAX - 5];
        let mut n = encode_vlq(&mut buf, msgid);
        for a in args {
            match a {
                Arg::Int(v) => n += encode_vlq(&mut buf[n..], *v),
                Arg::Buf(d) => {
                    buf[n] = d.len() as u8;
                    buf[n + 1..n + 1 + d.len()].copy_from_slice(d);
                    n += 1 + d.len();
                }
            }
        }
        self.send_raw(b, &buf[..n]);
    }

    fn send_raw(&mut self, b: &mut impl Board, payload: &[u8]) {
        let mut out = [0u8; MESSAGE_MAX];
        let n = encode_block(&mut out, self.next_seq, payload);
        b.write(&out[..n]);
    }
}

